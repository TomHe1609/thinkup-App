"""Generate complete palettes from the existing colour tokens; no layout changes."""
from pathlib import Path
import colorsys
import json
import re

ROOT = Path(__file__).resolve().parent.parent
html = (ROOT / 'index.html').read_text(encoding='utf-8')
base = re.search(r':root\{(--c-[^}]+)\}', html).group(1)
colours = dict(re.findall(r'--c-([0-9a-f]{6,8}):(#[0-9a-f]{6,8})', base))
themes = json.loads((ROOT / 'appearance-palettes.json').read_text(encoding='utf-8'))['themes']

def hex_rgb(r, g, b):
    return '#' + ''.join(f'{max(0,min(255,round(x*255))):02x}' for x in (r,g,b))

def blend(a, b, amount):
    av = [int(a[i:i+2],16)/255 for i in (1,3,5)]
    bv = [int(b[i:i+2],16)/255 for i in (1,3,5)]
    return hex_rgb(*(x*(1-amount)+y*amount for x,y in zip(av,bv)))

def dark(code, p):
    rgb = code[:6]
    alpha = code[6:]
    r,g,b = [int(rgb[i:i+2],16)/255 for i in (0,2,4)]
    h,l,s = colorsys.rgb_to_hls(r,g,b)
    h *= 360
    status = s > .13 and (h < 70 or 100 < h < 185 or h >= 310)
    if status or l < .035:
        result = '#' + rgb
    elif l < .40:
        result = hex_rgb(*colorsys.hls_to_rgb(p['sh']/360,min(.48,l*p['lf']),min(.5,p['ss']*(.65+s))))
    elif l > .94:
        result = hex_rgb(*colorsys.hls_to_rgb(p['sh']/360,l,min(.28,p['ss']*.5)))
    else:
        target_h = p['h'] if s > .25 else p['sh']
        target_s = min(.75,p['s']*(.3+s*.8)) if s > .25 else p['ss']*.48
        result = hex_rgb(*colorsys.hls_to_rgb(target_h/360,l,target_s))
    exact = {'15172b':p['bg'],'141527':p['bg'],'151527':p['bg'],'241f37':p['panel'],'1e1e33':p['panel'],'8060ad':p['action']}
    return exact.get(rgb,result)+alpha

def light(code, p):
    rgb, alpha = code[:6], code[6:]
    r,g,b = [int(rgb[i:i+2],16)/255 for i in (0,2,4)]
    h,l,s = colorsys.rgb_to_hls(r,g,b)
    h *= 360
    # Existing dark surfaces become paper; text becomes ink. Status colours keep meaning.
    if l < .035:
        result = '#000000'
        if alpha:
            alpha = f'{round(int(alpha,16)*.25):02x}'
    elif s > .13 and (h < 70 or 100 < h < 185 or h >= 310):
        if 100 < h < 185:
            result = '#e5f5ec' if l < .30 else '#267049' if l < .60 else '#1b5737'
        elif 35 < h < 70:
            result = '#fff1cc' if l < .30 else '#a46f15' if l < .60 else '#735012'
        else:
            result = '#fce9ed' if l < .30 else '#a5364e' if l < .60 else '#8b263e'
    elif l < .28:
        result = blend(p['panel'],p['soft'],max(0,min(1,(l-.06)/.22)))
    elif l < .43:
        result = p['line']
    elif l > .90:
        result = p['ink']
    elif s > .25:
        result = p['accent']
    else:
        result = p['muted']
    exact = {'15172b':p['bg'],'141527':p['bg'],'151527':p['bg'],'241f37':p['panel'],'1e1e33':p['panel'],'8060ad':p['action'],'ffffff':p['ink']}
    return exact.get(rgb,result)+alpha

rules = ['/* Generated by scripts/build-appearance.py. Existing layout and four dark palettes stay intact. */']
for theme in themes:
    for mode in ['dark','light']:
        if mode == 'dark' and theme['id'] not in ['forest','rose']:
            continue
        p = theme[mode]
        selector = ':root[data-theme="'+theme['id']+'"]' if mode == 'dark' else ':root[data-color-mode="light"][data-theme="'+theme['id']+'"]'
        values = [f'--c-{code}:{dark(code,p) if mode=="dark" else light(code,p)}' for code in sorted(colours)]
        values += [f'--theme-bg:{p["bg"]}',f'--theme-panel:{p["panel"]}',f'--theme-accent:{p["accent"]}',f'--theme-action:{p["action"]}',f'--theme-action-text:{p["actionText"]}']
        if mode == 'light':
            values += [f'--theme-ink:{p["ink"]}',f'--theme-muted:{p["muted"]}',f'--theme-soft:{p["soft"]}',f'--theme-control-line:{p["control"]}']
        rules.append(selector+'{'+ ';'.join(values)+'}')

